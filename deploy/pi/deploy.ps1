# Rebuild ARMv6 kindle-shazam from config.local.json, install on the Pi,
# and (if mounted) point the Kindle server.url at kindle_server_url.
# Usage (repo root):  powershell -File deploy/pi/deploy.ps1
$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
Set-Location $Root

$cfgPath = Join-Path $Root 'config.local.json'
if (-not (Test-Path $cfgPath)) {
  throw "Missing $cfgPath — copy config.example.json to config.local.json and fill in values."
}
$cfg = Get-Content $cfgPath -Raw | ConvertFrom-Json
foreach ($req in 'lat','lon','place','solar_modbus','pi_ssh','kindle_server_url') {
  if ($null -eq $cfg.$req -or "$($cfg.$req)" -eq '') { throw "config.local.json missing '$req'" }
}
$unit = 1
if ($cfg.solar_unit) { $unit = [int]$cfg.solar_unit }

# Generate site defaults (gitignored) so values with spaces work on Windows.
$gen = Join-Path $Root 'cmd\kindle-shazam\z_site_defaults.go'
$place = [string]$cfg.place
$modbus = [string]$cfg.solar_modbus
function Esc([string]$s) { return $s.Replace('\', '\\').Replace('"', '\"') }
$genBody = @"
// Code generated by deploy/pi/deploy.ps1 from config.local.json; DO NOT EDIT.
package main

func init() {
	defaultLat = "$(Esc ([string]$cfg.lat))"
	defaultLon = "$(Esc ([string]$cfg.lon))"
	defaultPlace = "$(Esc $place)"
	defaultSolarModbus = "$(Esc $modbus)"
	defaultSolarUnit = "$unit"
}
"@
[System.IO.File]::WriteAllText($gen, ($genBody -replace "`r`n", "`n"))

Write-Host "Building linux/arm GOARM=6 with config.local.json..."
$env:GOOS = 'linux'
$env:GOARCH = 'arm'
$env:GOARM = '6'
$env:CGO_ENABLED = '0'
$out = Join-Path $Root 'kindle-shazam-linux-armv6'
& go build -o $out ./cmd/kindle-shazam
if ($LASTEXITCODE -ne 0) { throw 'go build failed' }
Remove-Item Env:GOOS, Env:GOARCH, Env:GOARM, Env:CGO_ENABLED -ErrorAction SilentlyContinue

$len = (Get-Item $out).Length
if ($len -lt 1MB) { throw "binary too small ($len bytes) — abort" }
Write-Host "binary $len bytes"

$key = Join-Path $env:USERPROFILE '.ssh\id_ed25519'
$sshArgs = @('-o', 'BatchMode=yes', '-o', 'IdentitiesOnly=yes', '-o', 'ConnectTimeout=20')
if (Test-Path $key) { $sshArgs = @('-i', $key) + $sshArgs }

$identify = 'audd'
if ($cfg.identify) { $identify = [string]$cfg.identify }
$auddToken = ''
if ($cfg.audd_api_token) { $auddToken = [string]$cfg.audd_api_token }
if ($identify -eq 'audd' -or $identify -eq 'aud' -or $identify -eq 'both' -or $identify -eq 'ab' -or $identify -eq 'race' -or $identify -eq '') {
  if (-not $auddToken -or $auddToken -eq 'YOUR_AUDD_API_TOKEN') {
    throw "config.local.json: set audd_api_token (AudD dashboard token) when identify is both/audd"
  }
}

# Secrets go in an env file on the Pi — never baked into the binary.
$envLocal = Join-Path $PSScriptRoot 'kindle-shazam.env'
$envBody = @"
IDENTIFY_PROVIDER=$identify
AUDD_API_TOKEN=$auddToken
"@
[System.IO.File]::WriteAllText($envLocal, ($envBody -replace "`r`n", "`n"))

Write-Host "Deploying to $($cfg.pi_ssh) (identify=$identify)..."
$svc = Join-Path $PSScriptRoot 'kindle-shazam.service'
& scp @sshArgs $out $svc $envLocal "$($cfg.pi_ssh):/tmp/"
if ($LASTEXITCODE -ne 0) { throw 'scp failed' }
Remove-Item -Force $envLocal -ErrorAction SilentlyContinue

$remote = 'set -e; test -s /tmp/kindle-shazam-linux-armv6; sudo install -m 755 /tmp/kindle-shazam-linux-armv6 /usr/local/bin/kindle-shazam; sudo install -m 644 /tmp/kindle-shazam.service /etc/systemd/system/kindle-shazam.service; sudo install -m 600 /tmp/kindle-shazam.env /etc/kindle-shazam.env; sudo rm -f /tmp/kindle-shazam.env; sudo mkdir -p /var/lib/kindle-shazam; sudo systemctl daemon-reload; sudo systemctl enable --now kindle-shazam; sudo systemctl restart kindle-shazam; sleep 5; systemctl is-active kindle-shazam; ls -la /usr/local/bin/kindle-shazam; curl -sS -m 15 http://127.0.0.1:8080/version; echo; curl -sS -m 5 "http://127.0.0.1:8080/log?follow=0" | head -n 8'
& ssh @sshArgs $cfg.pi_ssh $remote
if ($LASTEXITCODE -ne 0) { throw 'remote install failed' }

$url = [string]$cfg.kindle_server_url
Write-Host "Waiting up to 2 min for Kindle USB (plug in if needed)..."
$deadline = (Get-Date).AddMinutes(2)
$dl = $null
while ((Get-Date) -lt $deadline) {
  $vol = Get-Volume -ErrorAction SilentlyContinue | Where-Object { $_.FileSystemLabel -eq 'Kindle' -and $_.DriveLetter } | Select-Object -First 1
  if ($vol) { $dl = $vol.DriveLetter; break }
  Start-Sleep 3
}
if (-not $dl) {
  Write-Host 'Kindle not mounted; skipped extension sync'
} else {
  $destRoot = "${dl}:\extensions\kindleshazam"
  $srcRoot = Join-Path $Root 'kindle\extensions\kindleshazam'
  New-Item -ItemType Directory -Force -Path "$destRoot\bin" | Out-Null
  Copy-Item -Force (Join-Path $srcRoot 'config.xml') $destRoot
  Copy-Item -Force (Join-Path $srcRoot 'bin\*.sh') "$destRoot\bin\"
  # Bake real URL into server.url and the "Use Pi" menu action (repo keeps placeholder).
  [System.IO.File]::WriteAllText((Join-Path $destRoot 'server.url'), $url)
  $menu = Get-Content (Join-Path $srcRoot 'menu.json') -Raw
  $menu = $menu.Replace('http://PI_HOST:8080', $url)
  $menuPath = Join-Path $destRoot 'menu.json'
  [System.IO.File]::WriteAllText($menuPath, ($menu -replace "`r`n", "`n"))
  # Ensure LF on shell scripts on the device
  Get-ChildItem "$destRoot\bin\*.sh" | ForEach-Object {
    $t = [System.IO.File]::ReadAllText($_.FullName) -replace "`r`n", "`n" -replace "`r", "`n"
    [System.IO.File]::WriteAllText($_.FullName, $t)
  }
  Write-Host "Kindle ${dl}: synced extension; server.url -> $url"
  $shell = New-Object -ComObject Shell.Application
  $item = $shell.NameSpace(17).ParseName("${dl}:\")
  $verb = $item.Verbs() | Where-Object { ($_.Name -replace '&','') -match 'Eject' }
  if ($verb) { $verb.DoIt(); Start-Sleep 2; Write-Host "Ejected ${dl}:" }
}

Write-Host "DEPLOY_OK $url"
